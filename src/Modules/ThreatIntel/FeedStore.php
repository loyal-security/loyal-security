<?php
/**
 * Feed dataset cache — reads and writes verified remote signature files.
 *
 * @package LoyalSecurity
 */

namespace LoyalSecurity\Modules\ThreatIntel;

defined( 'ABSPATH' ) || exit;

use LoyalSecurity\Modules\Firewall\BanStore;

/**
 * Persists verified feed datasets to a private on-disk cache under
 * uploads/loyal-security/feed/.
 *
 * Files are written as return array(...)-style PHP so the WAF prepend can include
 * the WAF dataset directly at request time without JSON decoding.
 * A manifest.json tracks per-dataset versions and sha256 checksums.
 */
class FeedStore {

	private const DATASETS = array( 'waf', 'malware', 'patches', 'cve' );

	private const FILENAME_MAP = array(
		'waf'     => 'waf-remote.php',
		'malware' => 'malware-remote.php',
		'patches' => 'patches-remote.php',
		'cve'     => 'cve-db.php',
	);

	private string $dir;

	public function __construct() {
		$this->dir = BanStore::storage_dir() . '/feed';
	}

	public function feed_dir(): string {
		return $this->dir;
	}

	/**
	 * Write a verified dataset payload to disk as a PHP return-array file.
	 *
	 * @param string               $dataset One of: waf | malware | patches | cve.
	 * @param array<string, mixed> $data    Verified payload (must contain 'version' + 'rules').
	 */
	public function write( string $dataset, array $data ): bool {
		if ( ! in_array( $dataset, self::DATASETS, true ) ) {
			return false;
		}

		if ( ! is_dir( $this->dir ) && ! wp_mkdir_p( $this->dir ) ) {
			return false;
		}

		// Deny web access to the cache dir.
		$htaccess = $this->dir . '/.htaccess';
		if ( ! file_exists( $htaccess ) ) {
			file_put_contents( $htaccess, "Deny from all\n", LOCK_EX ); // phpcs:ignore WordPress.WP.AlternativeFunctions
		}
		$index = $this->dir . '/index.php';
		if ( ! file_exists( $index ) ) {
			file_put_contents( $index, "<?php // Silence is golden.\n", LOCK_EX ); // phpcs:ignore WordPress.WP.AlternativeFunctions
		}

		$version = isset( $data['version'] ) ? (string) $data['version'] : '';
		$rules   = isset( $data['rules'] )
			? (array) $data['rules']
			: ( isset( $data['entries'] ) ? (array) $data['entries'] : array() );

		$php = "<?php\n"
			. "// Auto-generated by Loyal Security ThreatIntel — do not edit.\n"
			. "defined( 'ABSPATH' ) || defined( 'LOYALSEC_WAF_PREPEND' ) || exit;\n"
			. "return " . var_export( array( 'version' => $version, 'rules' => $rules ), true ) . ";\n"; // phpcs:ignore WordPress.PHP.DevelopmentFunctions.error_log_var_export -- var_export() here serializes data into a cached PHP file for opcache-friendly reads, not debug output.

		$path = $this->dir . '/' . self::FILENAME_MAP[ $dataset ];
		if ( false === file_put_contents( $path, $php, LOCK_EX ) ) { // phpcs:ignore WordPress.WP.AlternativeFunctions
			return false;
		}
		// Same reasoning as FirewallModule::write_waf_config(): without this, a server running
		// opcache.validate_timestamps=0 keeps serving the previous sync's compiled bytecode of
		// this file indefinitely — a fresh WAF/malware/patches/cve sync would silently never
		// take effect at request time despite the file on disk being correct.
		if ( function_exists( 'opcache_invalidate' ) ) {
			opcache_invalidate( $path, true );
		}

		$this->update_manifest( $dataset, $version, hash( 'sha256', $php ) );

		/**
		 * Fires after ANY feed dataset is written to the cache — distinct from the
		 * cve-only `loyalsec_feed_updated` hook below. Consumers that care about a specific
		 * dataset (e.g. FirewallModule refreshing the prepend's config snapshot after a
		 * 'waf'/'patches' sync) should filter on $dataset themselves.
		 *
		 * @since 1.3.0
		 *
		 * @param string                            $dataset Dataset name: waf|malware|patches|cve.
		 * @param array<int, array<string, mixed>>   $rules   The newly-written rules/entries.
		 */
		do_action( 'loyalsec_feed_dataset_updated', $dataset, $rules );

		if ( 'cve' === $dataset && ! empty( $rules ) ) {
			/**
			 * Fires after a CVE advisory dataset is written to the feed cache.
			 *
			 * Consumers (e.g. AutoPatch) can react to fresh CVE advisories — each entry is
			 * the verified advisory array as delivered by the feed.
			 *
			 * @since 1.0.0
			 *
			 * @param array<int, array<string, mixed>> $advisories Newly-written CVE advisories.
			 */
			do_action( 'loyalsec_feed_updated', $rules );
		}

		return true;
	}

	/**
	 * Return the cached rules array for a dataset, or null if absent/corrupt.
	 *
	 * @return array<int, array<string, mixed>>|null
	 */
	public function get_rules( string $dataset ): ?array {
		if ( ! in_array( $dataset, self::DATASETS, true ) ) {
			return null;
		}
		$path = $this->dir . '/' . ( self::FILENAME_MAP[ $dataset ] ?? '' );
		if ( ! is_file( $path ) ) {
			return null;
		}
		try {
			$data = include $path;
		} catch ( \Throwable $e ) {
			return null;
		}
		if ( ! is_array( $data ) || ! isset( $data['rules'] ) || ! is_array( $data['rules'] ) ) {
			return null;
		}
		return $data['rules'];
	}

	/**
	 * Versions + checksums for all cached datasets.
	 *
	 * @return array<string, array{ version: string, checksum: string, updated: string }>
	 */
	public function get_manifest(): array {
		$path = $this->dir . '/manifest.json';
		if ( ! is_file( $path ) ) {
			return array();
		}
		$raw  = file_get_contents( $path ); // phpcs:ignore WordPress.WP.AlternativeFunctions
		$data = json_decode( (string) $raw, true );
		return is_array( $data ) ? $data : array();
	}

	private function update_manifest( string $dataset, string $version, string $checksum ): void {
		$manifest = $this->get_manifest();
		$manifest[ $dataset ] = array(
			'version'  => $version,
			'checksum' => $checksum,
			'updated'  => gmdate( 'Y-m-d H:i:s' ),
		);
		file_put_contents( // phpcs:ignore WordPress.WP.AlternativeFunctions
			$this->dir . '/manifest.json',
			(string) wp_json_encode( $manifest ),
			LOCK_EX
		);
	}
}
