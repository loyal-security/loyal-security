<?php
/**
 * Standalone-recovery authentication and state.
 *
 * @package TotalSecurityWP
 */

namespace TotalSecurityWP\Modules\Backup;

defined( 'ABSPATH' ) || exit;

/**
 * Manages the standalone recovery tool — a self-contained PHP script that can restore a backup
 * even when WordPress cannot boot.
 *
 * The plugin never writes that script to the server itself. When the administrator enables
 * recovery, a secret token is minted and only a **bcrypt hash** of it is stored, together with
 * the backups path and brute-force lockout counters, in a guarded state file under the plugin's
 * private uploads directory (denied to the web by .htaccess/web.config, and unreadable as PHP
 * without the guard constant). The administrator then downloads the tool from the dashboard
 * ({@see \TotalSecurityWP\Rest\Controllers\BackupController::recovery_download()}) and uploads it
 * to their server under a name of their choosing; the downloaded copy carries the absolute path
 * of that state file and of the WordPress install, so it works wherever it is placed and keeps
 * working across plugin updates. See {@see RecoveryScriptTemplate} for the tool's source.
 *
 * The plaintext token is shown to the operator exactly once, on generation.
 */
class RecoveryAuth {

	private const GUARD = 'TOTALSECWP_RECOVERY'; // phpcs:ignore WordPress.NamingConventions.PrefixAllGlobals.VariableConstantNameFound -- the sniff can't resolve the class-constant reference; the literal value it defines is already prefixed.

	/** Absolute path to the recovery state file ('' when uploads is unavailable). */
	public function state_file(): string {
		$dir = $this->recovery_dir();
		return '' === $dir ? '' : $dir . '/recovery-state.php';
	}

	/**
	 * Source of the standalone recovery tool, with this site's paths built in — returned for
	 * download, never written to disk by the plugin.
	 */
	public function script_source(): string {
		return RecoveryScriptTemplate::render(
			array(
				'state_file' => wp_normalize_path( $this->state_file() ),
				'wp_root'    => untrailingslashit( wp_normalize_path( \TotalSecurityWP\Support\Paths::root() ) ),
				'wp_config'  => wp_normalize_path( \TotalSecurityWP\Support\Paths::wp_config() ),
			)
		);
	}

	/**
	 * Private, web-denied directory for the state file, inside the plugin's uploads storage.
	 */
	private function recovery_dir(): string {
		$storage = \TotalSecurityWP\Modules\Firewall\BanStore::storage_dir();
		if ( '' === $storage ) {
			return '';
		}
		$dir = $storage . '/recovery';
		if ( ! is_dir( $dir ) ) {
			wp_mkdir_p( $dir );
		}
		if ( ! is_file( $dir . '/index.php' ) ) {
			\TotalSecurityWP\Support\Filesystem::write( $dir . '/index.php', "<?php\n// Silence is golden.\n" );
		}
		if ( ! is_file( $dir . '/.htaccess' ) ) {
			\TotalSecurityWP\Support\Filesystem::write( $dir . '/.htaccess', "Order deny,allow\nDeny from all\n<IfModule mod_authz_core.c>\n\tRequire all denied\n</IfModule>\n" );
		}
		if ( ! is_file( $dir . '/web.config' ) ) {
			\TotalSecurityWP\Support\Filesystem::write( $dir . '/web.config', "<configuration>\n\t<system.webServer>\n\t\t<authorization>\n\t\t\t<deny users=\"*\" />\n\t\t</authorization>\n\t</system.webServer>\n</configuration>\n" );
		}
		return $dir;
	}

	/**
	 * Read the raw state array (defining the guard so the state file yields its data).
	 *
	 * @return array<string,mixed>
	 */
	public function read_state(): array {
		$file = $this->state_file();
		if ( '' === $file || ! is_file( $file ) ) {
			return array();
		}
		if ( ! defined( self::GUARD ) ) {
			define( self::GUARD, true ); // phpcs:ignore WordPress.NamingConventions.PrefixAllGlobals.VariableConstantNameFound -- the sniff can't resolve self::GUARD to its literal value ('TOTALSECWP_RECOVERY'), which is already correctly prefixed.
		}
		$data = include $file;
		return is_array( $data ) ? $data : array();
	}

	private function write_state( array $state ): bool {
		$file = $this->state_file();
		if ( '' === $file ) {
			return false;
		}
		$php = "<?php\n"
			. "// Auto-generated by Loyal Security. Holds a bcrypt token hash only — no plaintext secret.\n"
			. "defined( '" . self::GUARD . "' ) || exit;\n"
			. 'return ' . var_export( $state, true ) . ";\n"; // phpcs:ignore WordPress.PHP.DevelopmentFunctions.error_log_var_export -- serializes state as valid PHP source for a fast native include, not debug output.
		$ok = \TotalSecurityWP\Support\Filesystem::write( $file, $php );
		if ( $ok ) {
			\TotalSecurityWP\Support\Filesystem::chmod( $file, 0600 );
		}
		return $ok;
	}

	/**
	 * Whether standalone recovery is currently enabled.
	 */
	public function is_enabled(): bool {
		$s = $this->read_state();
		return ! empty( $s['enabled'] ) && ! empty( $s['token_hash'] );
	}

	/**
	 * Operator-facing status (never exposes the hash or OTP secret).
	 *
	 * @return array{enabled:bool,created:string,otp_enabled:bool}
	 */
	public function status(): array {
		$s = $this->read_state();
		return array(
			'enabled'     => ! empty( $s['enabled'] ) && ! empty( $s['token_hash'] ),
			'created'     => (string) ( $s['created'] ?? '' ),
			'otp_enabled' => ! empty( $s['otp_enabled'] ),
		);
	}

	/**
	 * Enable recovery and mint a new token. Returns the plaintext token ONCE.
	 *
	 * When $otp is true a TOTP secret is also generated and stored so the recovery tool
	 * additionally requires a one-time code. The secret is returned ONCE (alongside the token)
	 * so the operator can enrol it in an authenticator app.
	 *
	 * @param bool $otp Whether to also require a one-time password.
	 * @return array{ok:bool,token?:string,otp_secret?:string,message?:string}
	 */
	public function enable( bool $otp = false ): array {
		$token = \TotalSecurityWP\Support\Crypto::token( 24 );
		$hash  = password_hash( $token, PASSWORD_DEFAULT );
		if ( ! is_string( $hash ) ) {
			return array( 'ok' => false, 'message' => __( 'Could not hash the recovery token.', 'loyal-security' ) );
		}

		$otp_secret = '';
		if ( $otp ) {
			$otp_secret = ( new \TotalSecurityWP\Modules\Auth\Totp() )->generate_secret();
		}

		$ok = $this->write_state( array(
			'enabled'     => true,
			'token_hash'  => $hash,
			'storage'     => wp_normalize_path( ( new BackupStore() )->dir() ),
			'created'     => gmdate( 'Y-m-d H:i:s' ),
			'attempts'    => 0,
			'lock_until'  => 0,
			'otp_enabled' => $otp,
			'otp_secret'  => $otp_secret,
		) );
		if ( ! $ok ) {
			return array( 'ok' => false, 'message' => __( 'Could not write the recovery state file (check that the uploads folder is writable).', 'loyal-security' ) );
		}

		$result = array( 'ok' => true, 'token' => $token );
		if ( $otp ) {
			$result['otp_secret'] = $otp_secret;
		}
		return $result;
	}

	/**
	 * Disable recovery: zeroes the secret, so every downloaded copy of the tool stops working.
	 */
	public function disable(): bool {
		return $this->write_state( array(
			'enabled'     => false,
			'token_hash'  => '',
			'storage'     => '',
			'created'     => '',
			'attempts'    => 0,
			'lock_until'  => 0,
			'otp_enabled' => false,
			'otp_secret'  => '',
		) );
	}
}
